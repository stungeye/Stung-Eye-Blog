#!/usr/bin/env node
// Generate the legacy-URL redirects for the Cloudflare Worker (Phase C, C3.1/C3.3).
//
// Writes:
//   _redirects             static + dynamic rules, applied by Workers static assets
//                          before any asset is matched (limits: 2,000 static, 100 dynamic)
//   worker/post-view.json  old CodeIgniter item id -> day page, used by worker/index.js
//
// Inputs (all in this repo): export/redirects.csv (MT entry URLs), export/ci_items.json and
// export/ci_days.json (CodeIgniter items), src/posts/ (images), tools/legacy-redirects.json
// (hand-decided extra rules). Unpadded /archive/by_date/ URLs and /post/view/ID are handled by
// worker/index.js, which only runs when no asset matches (they can't be expressed here).
//
// Usage: node tools/build-redirects.mjs
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, p), "utf-8");
const STATIC_LIMIT = 2000;
const DYNAMIC_LIMIT = 100;

function parseCsvLine(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

const slash = (u) => (u.endsWith("/") ? u : u + "/");
const dayExists = (u) => {
  try { return statSync(join(ROOT, "src/posts", u.replace(/^\/archive\/by_date\//, ""), "index.md")).isFile(); }
  catch { return false; }
};

const staticRules = [];
const dynamicRules = [];
const seen = new Set();
function add(list, from, to, why) {
  if (seen.has(from)) throw new Error(`duplicate source ${from}`);
  if (/\s/.test(from) || /\s/.test(to)) throw new Error(`whitespace in rule ${from} ${to}`);
  seen.add(from);
  list.push({ from, to, why });
}

// 1. Hand-decided rules (PLAN F36 etc.).
const extra = JSON.parse(read("tools/legacy-redirects.json"));
for (const r of extra.static) add(staticRules, r.from, r.to, "extra");

// 2. Movable Type entry archives (2002–2008): one per published entry.
const csv = read("export/redirects.csv").trim().split("\n").slice(1);
const mtYears = new Set();
for (const line of csv) {
  const f = parseCsvLine(line);
  const [legacy, , day] = f;
  if (!legacy || !day) continue;
  const to = slash(day);
  if (!dayExists(to)) throw new Error(`MT target missing: ${legacy} -> ${to}`);
  add(staticRules, legacy, to, "mt-entry");
  mtYears.add(legacy.split("/")[2]);
}

// 3. MT year indexes (static, so they win over the category rules below).
for (const y of [...mtYears].sort()) {
  for (const s of [`/archives/${y}`, `/archives/${y}/`, `/archives/${y}/index.php`, `/archives/${y}/index.html`]) {
    add(staticRules, s, `/archive/by_date/${y}/`, "mt-year");
  }
}

// 4. CodeIgniter-era photo copies: /public/images/item_images/<file> -> the day folder copy.
const ciDays = new Set(JSON.parse(read("export/ci_days.json")).map((d) => d.date));
const byName = new Map();
const subdirs = (...p) =>
  readdirSync(join(ROOT, "src/posts", ...p)).filter((n) => /^\d+$/.test(n) && statSync(join(ROOT, "src/posts", ...p, n)).isDirectory());
for (const y of subdirs()) {
  for (const m of subdirs(y)) {
    for (const d of subdirs(y, m)) {
      for (const f of readdirSync(join(ROOT, "src/posts", y, m, d))) {
        if (f === "index.md") continue;
        if (!byName.has(f)) byName.set(f, []);
        byName.get(f).push(`${y}-${m}-${d}`);
      }
    }
  }
}
for (const [name, days] of [...byName].sort()) {
  if (days.length !== 1 || !ciDays.has(days[0])) continue;
  if (!/^[A-Za-z0-9._-]+$/.test(name)) continue;
  const [y, m, d] = days[0].split("-");
  add(staticRules, `/public/images/item_images/${name}`, `/archive/by_date/${y}/${m}/${d}/${name}`, "ci-image");
}

// 5. Dynamic rules (placeholders/splats), after all static ones.
for (const r of extra.dynamic) add(dynamicRules, r.from, r.to, "extra");

if (staticRules.length > STATIC_LIMIT) throw new Error(`${staticRules.length} static rules > ${STATIC_LIMIT}`);
if (dynamicRules.length > DYNAMIC_LIMIT) throw new Error(`${dynamicRules.length} dynamic rules > ${DYNAMIC_LIMIT}`);

const lines = [
  "# Generated by tools/build-redirects.mjs — do not edit by hand.",
  `# ${staticRules.length} static + ${dynamicRules.length} dynamic rules.`,
  ...staticRules.map((r) => `${r.from} ${r.to} 301`),
  ...dynamicRules.map((r) => `${r.from} ${r.to} 301`),
  "",
];
writeFileSync(join(ROOT, "_redirects"), lines.join("\n"));

// /post/view/<id>[/<slug>] -> the item's day page (worker/index.js).
const postView = {};
for (const it of JSON.parse(read("export/ci_items.json"))) {
  const to = slash(it.canonical_day_url);
  if (!dayExists(to)) throw new Error(`CI item ${it.id} target missing: ${to}`);
  postView[it.id] = to;
}
mkdirSync(join(ROOT, "worker"), { recursive: true });
writeFileSync(join(ROOT, "worker/post-view.json"), JSON.stringify(postView, null, 0) + "\n");

const counts = {};
for (const r of staticRules) counts[r.why] = (counts[r.why] || 0) + 1;
console.log(`_redirects: ${staticRules.length} static (${JSON.stringify(counts)}), ${dynamicRules.length} dynamic`);
console.log(`worker/post-view.json: ${Object.keys(postView).length} items`);
